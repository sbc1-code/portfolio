import assert from 'node:assert/strict';
import { DEFAULTS, evaluateScenario, moneyInput } from './model.mjs';

const sample = changes => ({ ...DEFAULTS.a, ...changes });
let result = evaluateScenario(sample({}), '10000');
assert.equal(result.valid, true);
assert.equal(result.net, 918500, 'Public example: 10,000 minus 815 = 9,185');
assert.equal(result.gap, 81500);
assert.equal(result.total, 1206000);
assert.equal(result.cost, 287500, 'Fee included once in cost above cash received');
assert.equal(evaluateScenario(sample({ fee: '0' }), '10000').gap, 0);
assert.equal(evaluateScenario(sample({}), '9000').gap, -18500);
assert.equal(evaluateScenario(sample({ fee: '10000' }), '10000').valid, false);
assert.equal(evaluateScenario(sample({ fee: '10001' }), '10000').valid, false);
assert.equal(evaluateScenario(sample({ fee: '' }), '10000').state, 'incomplete');
assert.equal(evaluateScenario(sample({ monthly: '' }), '10000').valid, false);
assert.equal(evaluateScenario(sample({ count: '36.5' }), '10000').valid, false);
assert.equal(evaluateScenario(sample({ count: '0' }), '10000').valid, false);
assert.equal(evaluateScenario(sample({ count: '601' }), '10000').valid, false);
assert.equal(evaluateScenario(sample({ monthly: '1' }), '10000').valid, false);
assert.equal(evaluateScenario(sample({}), '').net, 918500);
assert.equal(evaluateScenario(sample({}), '').gap, null);
assert.ok(evaluateScenario(sample({}), '').needError);
assert.equal(moneyInput('1.01').cents, 101);
assert.ok(moneyInput('1.001').error);
assert.ok(moneyInput('-1').error);
assert.ok(moneyInput('Infinity').error);
assert.ok(moneyInput('1000001').error);
assert.ok(moneyInput('1e4').error);
assert.equal(moneyInput('0', { zero: true }).cents, 0);
console.log('25 calculation and boundary checks passed.');
